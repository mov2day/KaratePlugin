/** Pure protected output writer: never clobbers user edits. No vscode, no node fs. */
import { createHash } from 'crypto';
import type { FsLike } from '../config/ProjectDiscovery';

export interface HashStore {
    get(path: string): string | undefined;
    set(path: string, hash: string): void;
}

export type WritableFs = FsLike & { write(p: string, content: string): void };

export interface WriteFile {
    path: string;
    content: string;
    owner: 'user' | 'generated';
    /** Source reference shown in the generated header (feature files only). */
    source?: string;
    /** A failed pre-write validation must not replace an existing feature. */
    forceSideBySide?: boolean;
}

export interface WriteOptions {
    generatorVersion: string;
    /** Optional real workspace root for adapters that use absolute paths. */
    workspaceRoot?: string;
}

export interface WriteReport {
    created: string[];
    updated: string[];
    skippedExisting: string[];
    sideBySide: { path: string; generatedPath: string }[];
}

export const HEADER_RE = /^# Generated by Karate Test Management [^|\n]*\| source: [^|\n]*\| hash: ([0-9a-f]{64})[ \t]*\n/;

const normalize = (text: string): string => text.replace(/\r\n/g, '\n');
export const sha256 = (text: string): string => createHash('sha256').update(text, 'utf8').digest('hex');
const slash = (p: string): string => p.replace(/\\/g, '/');
const isSafeWorkspacePath = (p: string): boolean => !/^([A-Za-z]:)?\//.test(slash(p)) && !slash(p).split('/').some(part => part === '..');
const isWithinRoot = (p: string, root: string): boolean => {
    const normalizedRoot = slash(root).replace(/\/+$/, '');
    const normalizedPath = slash(p);
    return normalizedPath.startsWith(`${normalizedRoot}/`) && !normalizedPath.slice(normalizedRoot.length + 1).split('/').some(part => part === '..');
};

export function splitHeader(text: string): { body: string; headerHash?: string } {
    const m = HEADER_RE.exec(text);
    return m ? { body: text.slice(m[0].length), headerHash: m[1] } : { body: text };
}

export function generatedSiblingPath(path: string): string {
    const slash = Math.max(path.lastIndexOf('/'), path.lastIndexOf('\\'));
    const dot = path.lastIndexOf('.');
    return dot > slash + 1 ? `${path.slice(0, dot)}.generated${path.slice(dot)}` : `${path}.generated`;
}

function render(file: WriteFile, version: string): { text: string; hash: string } {
    const body = normalize(file.content);
    const hash = sha256(body);
    const text = file.owner === 'generated' && file.path.endsWith('.feature')
        ? `# Generated by Karate Test Management ${version} | source: ${(file.source ?? 'unknown').replace(/[|\r\n\s]+/g, ' ').trim()} | hash: ${hash}\n${body}`
        : body;
    return { text, hash };
}

/** Find a safe generated sibling. An unchanged prior sibling is reusable; user content is never clobbered. */
function siblingPath(path: string, fsApi: WritableFs, history: HashStore): string {
    let candidate = generatedSiblingPath(path);
    while (fsApi.exists(candidate)) {
        const current = splitHeader(normalize(fsApi.read(candidate)));
        const hash = sha256(current.body);
        if (hash === history.get(candidate) || hash === current.headerHash) {return candidate;}
        candidate = generatedSiblingPath(candidate);
    }
    return candidate;
}

/** Thrown when a file write fails mid-run; `partial` reports what was already written. */
export class WriteError extends Error {
    constructor(readonly failedPath: string, readonly partial: WriteReport, cause: unknown) {
        super(cause instanceof Error ? cause.message : String(cause));
        this.name = 'WriteError';
    }
}

export const OutputWriter = {
    write(files: WriteFile[], fsApi: WritableFs, history: HashStore, options: WriteOptions): WriteReport {
        const report: WriteReport = { created: [], updated: [], skippedExisting: [], sideBySide: [] };
        for (const file of files) {
            try {
                if (!isSafeWorkspacePath(file.path) && !(options.workspaceRoot && isWithinRoot(file.path, options.workspaceRoot))) {
                    throw new Error(`Refusing to write path outside the workspace: ${file.path}`);
                }
                const out = render(file, options.generatorVersion);
                if (file.forceSideBySide) {
                    const generatedPath = siblingPath(file.path, fsApi, history);
                    fsApi.write(generatedPath, out.text);
                    history.set(generatedPath, out.hash);
                    report.sideBySide.push({ path: file.path, generatedPath });
                    continue;
                }
                if (!fsApi.exists(file.path)) {
                    fsApi.write(file.path, out.text);
                    history.set(file.path, out.hash);
                    report.created.push(file.path);
                    continue;
                }
                if (file.owner === 'user') {
                    report.skippedExisting.push(file.path);
                    continue;
                }
                const current = splitHeader(normalize(fsApi.read(file.path)));
                const currentHash = sha256(current.body);
                if (currentHash === history.get(file.path) || currentHash === current.headerHash) {
                    fsApi.write(file.path, out.text);
                    history.set(file.path, out.hash);
                    report.updated.push(file.path);
                } else {
                    const generatedPath = siblingPath(file.path, fsApi, history);
                    fsApi.write(generatedPath, out.text);
                    history.set(generatedPath, out.hash);
                    report.sideBySide.push({ path: file.path, generatedPath });
                }
            } catch (e) {
                throw new WriteError(file.path, report, e);
            }
        }
        return report;
    }
};
